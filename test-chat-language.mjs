import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {initialDrawing} from './lib/drawings/model.mjs';
import {renderDrawing} from './lib/drawings/render.mjs';
import {messages,questionsFor,productTitlesKk,localizedSummary} from './app/chat-i18n.ts';
const data=JSON.parse(readFileSync('app/content.json','utf8'));
assert.equal(questionsFor('kk').length,9);
assert.deepEqual(questionsFor('kk').map(q=>q.key),questionsFor('ru').map(q=>q.key));
assert.deepEqual(Object.keys(messages.ru),Object.keys(messages.kk));
assert(data.catalog.every(p=>productTitlesKk[p.href]));
const spec=initialDrawing('Орындық','ені 1800 мм, биіктігі 800 мм, тереңдігі 450 мм','қалыңдығы 2 мм');
assert.equal(spec.kind,'bench');assert.deepEqual(spec.dimensions,{width:1800,height:800,depth:450,thickness:2});
const kk=renderDrawing({...spec,notes:'Клиенттің өзгермейтін мәтіні <script>'},'Орындық','TEST','kk');
const ru=renderDrawing(spec,'Скамейка','TEST');
assert(kk.includes('АЛДЫН АЛА СЫЗБА')&&kk.includes('Көлемді көрініс'));
assert(!kk.includes('Объёмный вид'));assert(ru.includes('Объёмный вид'));
assert(kk.includes('Клиенттің өзгермейтін мәтіні &lt;script&gt;'));
assert(localizedSummary(['Орындық'],'kk').includes('Бұйым: Орындық'));
console.log('Passed: nine matching question keys, complete RU/KK messages and product options, Kazakh dimension parsing, localized SVG, escaping and WhatsApp summary.');