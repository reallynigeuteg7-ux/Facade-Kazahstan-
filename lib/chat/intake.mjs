import products from '../catalog/products.json' with { type: 'json' };
import { initialDrawing } from '../drawings/model.mjs';
export function catalogMatch(text) {
  const match = text.match(
    /(?:PDF[-\s]*|страниц[аыуе]?\s*|стр[.\s]*|бет\s*|№\s*)(\d{1,2})|(?:^|\s)(\d{1,2})\s*бет/i,
  );
  return match
    ? products.find((p) => p.page === Number(match[1] || match[2]))
    : null;
}
export function isQuestion(text) {
  return /\?|^(?:сколько|как\s|какой\s|какая\s|какие\s|есть\sли|можно\sли|подскаж|посовет|что\s|нужна рекомендация|қанша|қалай|қандай|кеңес\s)/i.test(
    text.trim(),
  );
}
export function isRecommendationAnswer(step, text) {
  return (
    step === 3 &&
    /^(?:нужна рекомендация|подбер[её]т менеджер|кеңес қажет|менеджер таңдайды)[.!\s]*$/iu.test(
      text.trim(),
    )
  );
}
export function intakeError(step, value, answers, language = 'ru') {
  const kk = language === 'kk';
  if (
    step === 0 &&
    /(?<!\p{L})(?:и|және)(?!\p{L})/iu.test(value) &&
    [
      /(?:скаме|скамь|орындық)/iu,
      /(?:урн|қоқыс жәш)/iu,
      /кассет/iu,
      /сайдинг|панел/iu,
    ].filter((pattern) => pattern.test(value)).length > 1 &&
    !catalogMatch(value)
  )
    return kk
      ? 'Алдымен бір бұйымды таңдаңыз. Сақталғаннан кейін осы тапсырысқа келесі бұйымды қосуға болады; әрқайсысына жеке сызба жасалады.'
      : 'Сначала выберите одно изделие. После сохранения нажмите «Добавить изделие к этому заказу» — у каждой позиции будет свой чертёж.';
  if (
    step === 0 &&
    /(?:страниц|стр\.|PDF-|бет)/i.test(value) &&
    !catalogMatch(value)
  )
    return kk
      ? 'Каталогта 22 бет бар. 1–22 аралығындағы бетті таңдаңыз.'
      : 'В каталоге 22 страницы. Укажите страницу от 1 до 22.';
  if (step === 2 && /^-|^0(?:\D|$)/.test(value.trim()))
    return kk
      ? 'Саны нөлден үлкен болуы керек.'
      : 'Количество должно быть больше нуля.';
  if (step === 4) {
    try {
      const spec = initialDrawing(answers[0], answers[1], answers[3], value);
      if (spec.warnings.length)
        return kk
          ? 'Аралықтар мен құрылым өлшемдерін тексеріңіз. ' +
              spec.warnings.join(' ')
          : spec.warnings.join(' ');
    } catch (e) {
      return kk ? 'Өлшемдерді тексеріңіз.' : e.message;
    }
  }
  return '';
}
export function answerCatalogQuestion(question, answers, language = 'ru') {
  const kk = language === 'kk',
    p = catalogMatch(question) || catalogMatch(answers[0] || '');
  if (
    p &&
    /(цен|сто|баға|қанша|өлшем|размер|габарит|бет|страниц)/i.test(question)
  ) {
    const size = ['width', 'height', 'depth']
      .map((k) => p.dimensions[k] ?? '?')
      .join(' × ');
    return {
      answer: kk
        ? `${p.name}, PDF-${String(p.page).padStart(2, '0')}. Каталог бағасы (${p.priceDate}): ${p.price.toLocaleString('ru-RU')} ₸. Өлшемдері W × H × D: ${size} мм. «?» — өлшем көрсетілмеген. Соңғы бағаны менеджер растайды.`
        : `${p.name}, PDF-${String(p.page).padStart(2, '0')}. Цена в каталоге от ${p.priceDate}: ${p.price.toLocaleString('ru-RU')} ₸. Размеры W × H × D: ${size} мм. «?» означает, что размер не указан. Актуальную стоимость подтвердит менеджер.`,
      product: p,
    };
  }
  if (/цен|стоим|сколько|баға|қанша/i.test(question))
    return {
      answer: kk
        ? 'Бағаны салыстыру үшін каталог бетін таңдаңыз. Жеке өлшем, саны, материал және жабын бойынша соңғы есепті менеджер жасайды.'
        : 'Укажите страницу каталога — покажу цену из документа. Заказ по индивидуальным размерам менеджер рассчитает по количеству, материалу и покрытию.',
    };
  if (/достав|жеткіз/i.test(question))
    return {
      answer: kk
        ? 'Қазақстан бойынша жеткізу бар. Қала мен көлемді көрсетіңіз — менеджер құны мен мерзімін нақтылайды.'
        : 'Поставляем по Казахстану. Укажите город и объём заказа — менеджер уточнит стоимость и срок доставки.',
    };
  return null;
}
export function drawingQuestion(product, language = 'ru') {
  const kk = language === 'kk';
  if(catalogMatch(product))return kk
    ? 'Каталогтағы фотодағы пішінді негізге аламыз. Осы үлгіні қалдырамыз ба, әлде арқалығын, қалқасын немесе басқа бөлшегін өзгертеміз бе? «Фотодағыдай» деп жаза аласыз. Жасырын бөлшектерді маман нақтылайды.'
    : 'Берём за основу форму на фото выбранной модели. Оставляем как на фото или меняем спинку, козырёк либо другие детали? Можно написать «Как на фото». Скрытые узлы уточнит специалист.';
  if (/каркас|қаңқа|бесед|күрке|павильон/i.test(product)) return null;
  if (/скам|орындық/i.test(product))
    return kk
      ? 'Арқалығы мен шынтақшалары қажет пе? Отырғыштың биіктігі мен тереңдігін, тірек қимасын және каталог үлгісін көрсетіңіз.'
      : 'Нужны спинка и подлокотники? Укажите высоту и глубину сиденья, сечение опор и модель из каталога. Можно написать, что нужно уточнить.';
  if (/урн|контейнер|жәшік/i.test(product))
    return kk
      ? 'Пішіні қандай? Қақпағы, ішкі шелегі, тесіктері қажет пе? Каталог үлгісін көрсетіңіз.'
      : 'Какая форма нужна? Нужны крышка, внутреннее ведро, отверстия и крепление? Укажите модель каталога или опишите детали.';
  if (/кассет|панел|сайдинг|профил|подсистем/i.test(product))
    return kk
      ? 'Профильді, иілімдерді және тесіктерді сипаттаңыз. Сызба немесе каталог үлгісі бар ма?'
      : 'Укажите профиль, размеры загибов, отверстия и способ крепления. Есть готовый чертёж или обозначение модели?';
  return kk
    ? 'Пішінін, тесіктерін, бекітуін және каталог үлгісін сипаттаңыз. Белгісіз бөлшектерді менеджер нақтылайды.'
    : 'Опишите форму, отверстия, крепления и модель каталога. Неизвестные детали можно уточнить с менеджером.';
}
