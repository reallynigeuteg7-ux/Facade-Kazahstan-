export function localizedSummary(answers: string[], language: ChatLanguage) {
  const t = messages[language];
  return (
    t.summaryTitle +
    '\n\n' +
    questionsFor(language)
      .map((q, i) => q.label + ': ' + (answers[i] || t.notSpecified))
      .join('\n') +
    '\n\n' +
    t.summaryEnd
  );
}
