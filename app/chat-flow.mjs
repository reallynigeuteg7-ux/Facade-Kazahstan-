export function validateAnswer(index, value) {
  if (typeof value !== 'string' || !value.trim()) return 'Введите ответ.';
  if (value.length > 600) return 'Ответ должен быть не длиннее 600 символов.';
  if (index === 8 && !/^[+\d\s()-]{7,25}$/.test(value))
    return 'Проверьте номер телефона.';
  return '';
}
export function makeSummary(answers) {
  return (
    'Заявка с сайта Facade Kazahstan\n\n' +
    questions
      .map((q, i) => q.label + ': ' + (answers[i] || 'Не указано'))
      .join('\n') +
    '\n\nПрошу уточнить стоимость и условия изготовления.'
  );
}
